// Builds girs-index.js: the sample-data index the global search (girs-search.js) looks through.
// Run from the repo root after changing sample data:  node tools/build-search-index.js
const fs = require('fs'), vm = require('vm');

function pageData() {
  const s = fs.readFileSync('invoice-list-v2.html', 'utf8');
  const a = s.lastIndexOf('<script', s.indexOf('const IV_SEED')), st = s.indexOf('>', a) + 1, b = s.indexOf('class GirsPage', st);
  const ctx = { console, localStorage: { getItem: () => null }, window: {}, document: {}, location: { search: '' } };
  vm.createContext(ctx);
  return vm.runInContext(s.slice(st, b) + '\n;({ IV_ALL, IV_RDY, IV_CUST, IV_CHG, ivSt2 })', ctx);
}
const d = pageData();
const cn = (c) => (d.IV_CUST[c] || {}).name || c;

// Invoices: [no, type, bl, bkg, customer, container, vvd, date, amount + currency, port, invoice status]
const inv = d.IV_ALL.map((i) => {
  const tot = (i.lines || []).reduce((a, l) => a + (l[2] === 'USD' ? l[1] : 0), 0);
  return [i.no, i.type, i.bl, i.bkg, i.party || cn(i.cust), i.cntr, i.vvd, i.date, tot ? tot.toLocaleString('en-US', { minimumFractionDigits: 2 }) + ' USD' : '', i.port, d.ivSt2(i)];
});
// Ready to invoice B/Ls: [id, bl, bkg, customer, port, type, status, container, vvd]
const rdy = d.IV_RDY.map((r) => [r.id, r.bl, r.bkg, cn(r.cust), r.port, r.type, r.status, r.cntr, r.vvd]);
const cust = Object.keys(d.IV_CUST).map((k) => [k, d.IV_CUST[k].name, d.IV_CUST[k].addr || '']);
const chg = Object.keys(d.IV_CHG).map((k) => [k, d.IV_CHG[k]]);

// Master records: [page, group, code, title, detail]
const MASTERS = [['port-master.html', 'Port'], ['tax-setup.html', 'Tax code'], ['currency-master.html', 'Currency'], ['country-master.html', 'Country'],
  ['city-master.html', 'City'], ['exchange-rate-master.html', 'Exchange rate'], ['charge-master.html', 'Charge'], ['contract-master.html', 'Contract']];
const master = [];
MASTERS.forEach(([page, group]) => {
  const s = fs.readFileSync(page, 'utf8');
  const m = s.match(/const D = (\{.*?\});\n/s) || s.match(/const KIT_M = (\{.*?\});\n/s);
  if (!m) return;
  (JSON.parse(m[1]).recs || []).forEach((r) => {
    const v = r.v || {}, code = v.code || r.code || r.id;
    const extra = [v.unl, v.name !== r.title ? v.name : '', v.rate, v.ctry, v.st || r.st].filter(Boolean).join(' · ');
    master.push([page, group, code, r.title || v.name || code, extra]);
  });
});

// Screens: every side-menu item, with its menu section
const tpl = fs.readFileSync('invoice-list-v2.html', 'utf8');
const L = JSON.parse(tpl.match(/const L = Object\.assign\(\{\}, (\{.*?\})/)[1]);
const screens = [], seenS = {};
const re = /id="ng-(g\d)"|<a href="([^"]+)" class="nav-item[^"]*"(?: aria-current="page")? title="([^"]+)"/g;
let mm, grp = '';
while ((mm = re.exec(tpl))) {
  if (mm[1]) { grp = L[mm[1]] || ''; continue; }
  const t = mm[3].replace(/^\{\{shell\.l\.(\w+)\}\}$/, (x, k) => L[k] || k);
  if (seenS[mm[2]]) continue; seenS[mm[2]] = 1;
  screens.push([mm[2], t, grp]);
}

const out = '/* Generated by tools/build-search-index.js — sample data for the global search. Do not edit by hand. */\nwindow.GIRS_INDEX = ' +
  JSON.stringify({ screens, inv, rdy, cust, chg, master }) + ';\n';
fs.writeFileSync('girs-index.js', out);
console.log('girs-index.js', out.length, 'bytes ·', screens.length, 'screens,', inv.length, 'invoices,', rdy.length, 'B/Ls,', cust.length, 'customers,', chg.length, 'charges,', master.length, 'master records');
