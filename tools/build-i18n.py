"""Builds i18n-zh.js, i18n-es.js and i18n-ar.js from tools/i18n/*.tsv (en<TAB>zh<TAB>es<TAB>ar).
'#' in a phrase stands for any number; the runtime (girs-i18n.js) puts the real numbers back in order.
Run from the repo root:  python3 tools/build-i18n.py"""
import glob, json

LANGS = ['zh', 'es', 'ar']
# "<prefix> <code>" labels (row actions, selections) — the code stays as it is
TEMPLATES = {
    'Actions for {x}': ['{x} 的操作', 'Acciones de {x}', 'إجراءات {x}'],
    'All actions for {x}': ['{x} 的全部操作', 'Todas las acciones de {x}', 'كل إجراءات {x}'],
    'Select {x}': ['选择 {x}', 'Seleccionar {x}', 'تحديد {x}'],
    'Show charge lines of {x}': ['显示 {x} 的费用明细', 'Mostrar líneas de cargo de {x}', 'عرض بنود رسوم {x}'],
    'Include {x}': ['包含 {x}', 'Incluir {x}', 'تضمين {x}'],
    'Validation of {x}': ['{x} 的校验', 'Validación de {x}', 'التحقق من {x}'],
    'STP validation gates {x}': ['STP 校验关卡 {x}', 'Controles de validación STP {x}', 'بوابات التحقق STP {x}'],
    'Invoice {x}': ['发票 {x}', 'Factura {x}', 'الفاتورة {x}'],
    'Credit note {x}': ['贷项通知单 {x}', 'Nota de crédito {x}', 'الإشعار الدائن {x}'],
    'Receipt {x}': ['收据 {x}', 'Recibo {x}', 'الإيصال {x}'],
    'Due {x}': ['到期 {x}', 'Vence {x}', 'الاستحقاق {x}'],
    'Search “{x}” in Enquiry & Monitoring': ['在查询与监控中搜索“{x}”', 'Buscar «{x}» en Consulta y monitoreo', 'ابحث عن "{x}" في الاستعلام والمراقبة'],
    'No results for “{x}”': ['没有“{x}”的结果', 'Sin resultados para «{x}»', 'لا توجد نتائج لـ "{x}"'],
    'Show all {x} invoices in Invoice List': ['在发票列表中显示全部 {x} 张发票', 'Mostrar las {x} facturas en Lista de facturas', 'عرض كل الفواتير ({x}) في قائمة الفواتير'],
    'Language set to {x}': ['语言已设为 {x}', 'Idioma cambiado a {x}', 'تم ضبط اللغة على {x}'],
}

rows = {}
for f in sorted(glob.glob('tools/i18n/*.tsv')):
    for ln in open(f, encoding='utf-8'):
        ln = ln.rstrip('\n')
        if not ln.strip(): continue
        p = ln.split('\t')
        if len(p) != 4: raise SystemExit(f'{f}: bad line: {ln[:80]}')
        rows[' '.join(p[0].split())] = p[1:]

for i, lang in enumerate(LANGS):
    d = {k: v[i] for k, v in rows.items()}
    t = [[k, v[i]] for k, v in TEMPLATES.items()]
    js = ('/* Generated by tools/build-i18n.py — edit tools/i18n/*.tsv, not this file. */\n'
          'window.GIRS_I18N = ' + json.dumps({'lang': lang, 'dict': d, 'tpl': t}, ensure_ascii=False, separators=(',', ':')) + ';\n')
    open(f'i18n-{lang}.js', 'w', encoding='utf-8').write(js)
    print(f'i18n-{lang}.js', len(d), 'phrases', len(js), 'bytes')
